def extract_mermaid(text):
    if not text:
        return None
    match = re.search(
        r"```mermaid\s+(.*?)\s+```",
        text,
        re.DOTALL
    )

    if match:
        return match.group(1)

    return None


def _mcts_restriction(requirements: str) -> str | None:
    """Return an explicit requirement that prevents executing MCTS."""
    normalized = requirements.lower()
    restrictions = (
        r"no utilizar mcts",
        r"no usar mcts",
        r"sin seleccionar automáticamente",
        r"no .*optimización",
    )
    for restriction in restrictions:
        if re.search(restriction, normalized):
            return restriction
    return None


def run_mcts_from_blackboard(design: Blackboard) -> dict[str, object]:
    """Run MCTS only when the SES requirements authorize automatic selection."""
    requirements = design.ses_data["requirements"]
    restriction = _mcts_restriction(requirements)
    if restriction:
        return {
            "executed": False,
            "reason": f"MCTS no ejecutado por restricción: {restriction}",
        }

    if not re.search(r"\bclasificaci[oó]n\b|\bclassification\b", requirements, re.I):
        return {
            "executed": False,
            "reason": "No se pudo caracterizar un problema de clasificación.",
        }

    problem = {"objective": "Classification"}
    design.characterize_problem(
        "classification",
        "Selección de algoritmo para un problema de clasificación.",
        tuple(problem.items()),
    )
    iterations = int(os.environ.get("MCTS_ITERATIONS", "1000"))
    kb = build_demo_kb(random.Random(42))
    mcts = SemanticMCTS(kb, problem, reward_mode="paper", seed=7)
    selected = mcts.run(iterations)
    return {
        "executed": True,
        "problem": problem,
        "selected_design": selected.name,
        "reward": reward(kb, selected, mcts.w),
        "metrics": mcts.performance_report(),
    }

